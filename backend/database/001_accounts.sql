BEGIN;
SET LOCAL search_path = public;

CREATE TABLE IF NOT EXISTS app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(btrim(email))),
    password_hash varchar(255) NOT NULL,
    created_at timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS albums (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description text,
    created_at date NOT NULL,
    owner_id bigint NOT NULL REFERENCES app_users(id)
);

-- Pošpeši iskanje albumov prijavljenega uporabnika.
CREATE INDEX IF NOT EXISTS idx_albums_owner ON albums(owner_id);

CREATE TABLE IF NOT EXISTS photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename varchar(255),
    file_path varchar(255),
    uploaded_at timestamp(6),
    creation_date timestamp(6),
    favorite boolean NOT NULL DEFAULT false,
    album_id bigint NOT NULL REFERENCES albums(id)
);

COMMIT;
