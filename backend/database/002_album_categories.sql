BEGIN;
SET LOCAL search_path = public;
CREATE TABLE IF NOT EXISTS categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (length(btrim(name)) > 0),
    owner_id bigint NOT NULL REFERENCES app_users(id)
);
CREATE INDEX IF NOT EXISTS idx_categories_owner ON categories(owner_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_owner_name ON categories(owner_id, lower(name));
ALTER TABLE albums ADD COLUMN IF NOT EXISTS category_id bigint REFERENCES categories(id);
CREATE INDEX IF NOT EXISTS idx_albums_category ON albums(category_id);


DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'albums' AND column_name = 'category') THEN
        INSERT INTO categories (owner_id, name)
        SELECT DISTINCT owner_id, CASE category
            WHEN 'TRAVEL' THEN 'Potovanja' WHEN 'FAMILY' THEN 'Družina'
            WHEN 'FRIENDS' THEN 'Prijatelji' WHEN 'EVENTS' THEN 'Dogodki'
            WHEN 'NATURE' THEN 'Narava' ELSE 'Drugo' END
        FROM albums WHERE category IS NOT NULL
        ON CONFLICT DO NOTHING;
        UPDATE albums a SET category_id = c.id FROM categories c
        WHERE a.category_id IS NULL AND a.category IS NOT NULL AND c.owner_id = a.owner_id
          AND lower(c.name) = lower(CASE a.category
            WHEN 'TRAVEL' THEN 'Potovanja' WHEN 'FAMILY' THEN 'Družina'
            WHEN 'FRIENDS' THEN 'Prijatelji' WHEN 'EVENTS' THEN 'Dogodki'
            WHEN 'NATURE' THEN 'Narava' ELSE 'Drugo' END);
        ALTER TABLE albums DROP COLUMN category;
    END IF;
END $$;
COMMIT;
